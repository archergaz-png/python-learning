n = int(input("\n Введите количество чисел \n")) # Ввод количества чисел

numbers = [] #создает пустой список

for _ in range(n): # прогоняет программу n раз
    number = int(input("\n Введите число и нажмите ENTER \t")) # пользователь вводит последовательно числа
    numbers.append(number) # добавляет введенные числа в созданный пустой список

target = int(input("\n Введите искомое число \t")) # Ввод числа таргет

def count_value(numbers, target): # объявили функцию

    count = 0 # инициализирует счетчик чисел

    for number in numbers: # дословно: для введенных пользователем чисел в списке
        if number == target: # если число принадлежит списку, то
            count = count + 1 # увеличивает счетчик, если число в списке
    return count # вытакскивает посчитанные значения четных чисел из функции и возвращает в основную программу

result = count_value(numbers, target)
print (f"\n Искомое число встречается {result} раз(а)")