n = int(input("\n Введите количество чисел \n")) # Ввод количества чисел

numbers = [] #создает пустой список

for _ in range(n): # прогоняет программу n раз: ввели число - добавили в список - посчитали четные 
    number = int(input("\n Введите число и нажмите ENTER \t")) 
# пользователь вводит последовательно числа
    numbers.append(number) # добавляет введенные числа в созданный пустой список

def find_max (numbers):# объявили функцию 
    
    best = numbers [0] 
    
    for number in numbers: # дословно: для введенных пользователем чисел в списке
        if number > best: # если число ...
            best = number 
    return best # вытакскивает посчитанные значения чисел из функции и возвращает в основную программу

print("\n Максимум : ", find_max (numbers)) # вывод на экран 